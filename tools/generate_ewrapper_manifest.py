#!/usr/bin/env python3
"""Generate the callback forwarding manifest from IBKR's reviewed header."""

import argparse
import hashlib
import pathlib
import re
import sys


def split_parameters(text):
    if not text.strip():
        return []
    result = []
    start = 0
    angle = 0
    paren = 0
    for index, char in enumerate(text):
        if char == "<":
            angle += 1
        elif char == ">":
            angle -= 1
        elif char == "(":
            paren += 1
        elif char == ")":
            paren -= 1
        elif char == "," and angle == 0 and paren == 0:
            result.append(text[start:index].strip())
            start = index + 1
    result.append(text[start:].strip())
    return result


def normalize_parameter(parameter, index):
    parameter = " ".join(parameter.split())
    parameter = re.sub(r"\bContractDetails\b", "::ContractDetails", parameter)
    parameter = re.sub(r"(?<!:)\bContract\b", "::Contract", parameter)
    if parameter.endswith("&") or parameter.endswith("*"):
        return parameter + " arg{}".format(index), "arg{}".format(index)
    match = re.search(r"([A-Za-z_][A-Za-z0-9_]*)$", parameter)
    if not match or not parameter[: match.start()].strip():
        return parameter + " arg{}".format(index), "arg{}".format(index)
    return parameter, match.group(1)


def callbacks(block):
    block = block.replace("\\\n", " ")
    pattern = re.compile(r"\bX\((\w+),\s*\((.*?)\)\)\s*\\?", re.DOTALL)
    result = []
    for name, raw_parameters in pattern.findall(block):
        declarations = []
        arguments = []
        for index, parameter in enumerate(split_parameters(raw_parameters)):
            declaration, argument = normalize_parameter(parameter, index)
            declarations.append(declaration)
            arguments.append(argument)
        result.append((name, ", ".join(declarations), ", ".join(arguments)))
    return result


def macro(name, entries):
    lines = ["#define {}(X) \\".format(name)]
    for index, (callback, declarations, arguments) in enumerate(entries):
        suffix = " \\" if index + 1 != len(entries) else ""
        tagged = callback + "_tag()"
        if arguments:
            tagged += ", " + arguments
        lines.append(
            "  X({}, ({}), ({}), ({})){}".format(
                callback, declarations, arguments, tagged, suffix
            )
        )
    return "\n".join(lines)


def generate(source):
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    regular_start = source.index("#define EWrapper_methods_regular")
    regular_end = source.index("// protobuf", regular_start)
    proto_start = source.index("#define EWrapper_methods_proto", regular_end)
    proto_end = source.index("#else", proto_start)
    regular = callbacks(source[regular_start:regular_end])
    proto = callbacks(source[proto_start:proto_end])
    if len(regular) != 89 or len(proto) != 81:
        raise RuntimeError(
            "expected 89 traditional and 81 Protobuf callbacks, got {} and {}".format(
                len(regular), len(proto)
            )
        )
    return "\n".join(
        [
            "// Generated by tools/generate_ewrapper_manifest.py; do not edit.",
            "// EWrapper_prototypes.h sha256: {}".format(digest),
            "#pragma once",
            "",
            macro("IBAPI4GU_EWRAPPER_REGULAR_CALLBACKS", regular),
            "",
            macro("IBAPI4GU_EWRAPPER_PROTO_CALLBACKS", proto),
            "",
            "#define IBAPI4GU_EWRAPPER_CALLBACKS(X) \\",
            "  IBAPI4GU_EWRAPPER_REGULAR_CALLBACKS(X) \\",
            "  IBAPI4GU_EWRAPPER_PROTO_CALLBACKS(X)",
            "",
        ]
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.input.read_text(encoding="utf-8"))
    if args.check:
        actual = args.output.read_text(encoding="utf-8")
        if actual != generated:
            print("callback manifest is stale", file=sys.stderr)
            return 1
    else:
        args.output.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
